// Demonstra operações básicas de criação, ordenação e alteração de um array.
let num = [5, 8, 2, 9, 3];
num.sort(); // Organiza os valores em ordem crescente conforme a comparação padrão.
num.push(11); // Adiciona um novo valor ao final do vetor.
console.log(num);
console.log(`O vetor tem ${num.length} posição`);
console.log(`Oprimeiro valor do vetor é ${num[0]}`);
