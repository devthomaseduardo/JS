/*
Questão 2: Criar um objeto vazio e adicionar os campos usando
a notação de ponto.
*/

// 1. Declaração do objeto vazio
let person = {};

// 2. Adicionando as propriedades usando a notação de ponto (.)
person.nome = 'Thomas';
person.sobrenome = 'Nascimento';

// 3. Exibindo os campos individuais no console
console.log(person.nome); // Saída: Thomas
console.log(person.sobrenome); // Saída: Nascimento

// Exibindo o objeto completo
console.log(person);
// Saída: { nome: 'Thomas', sobrenome: 'Nascimento' }
