// Criamos o array inicial com 4 nomes
let names = ['Olivia', 'Emma', 'Mateo', 'Samuel'];

// Exibe o número de elementos no array (4)
console.log(names.length); // Saída: 4

// O método push() adiciona "Amelia" no FINAL do array
names.push('Amelia');

// Agora o tamanho do array passa a ser 5
console.log(names.length); // Saída: 5

// Exibe a lista completa atualizada com o novo nome
console.log(names); // Saída: ["Olivia", "Emma", "Mateo", "Samuel", "Amelia"]
